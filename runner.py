"""
runner.py
=========
Simulation Runner for the SCSE '26 Integration and Simulation project.

Runs a simple simulation that tests the navigation logic (decide_next_move)
generated by the Developer Agent against all possible scenarios, and stores
the result of the entire simulation in a JSON file called
simulation_report.json.

The report includes:
  - total number of scenarios
  - number of passed and failed scenarios
  - success rate (passed / total)
"""

import itertools
import json
import os

from generated.navigation_logic import decide_next_move

HERE = os.path.dirname(os.path.abspath(__file__))
ARTIFACTS_DIR = os.path.join(HERE, "artifacts")
REPORT_PATH = os.path.join(ARTIFACTS_DIR, "simulation_report.json")

VALID_ACTIONS = {"FORWARD", "LEFT", "RIGHT", "STOP"}

STATE_KEYS = [
    "goal_ahead",
    "goal_on_left",
    "goal_on_right",
    "front_blocked",
    "left_blocked",
    "right_blocked",
]


def expected_action(state):
    """The correct action for a state, according to the navigation rules.

    Decision order (matches the revised navigation logic):
      1) goal ahead and front clear          -> FORWARD
      2) goal on left and left clear         -> LEFT
      3) goal on right and right clear       -> RIGHT
      4) otherwise pick any clear direction to manoeuvre around the obstacle
         (prefer FORWARD, then LEFT, then RIGHT)
      5) only if ALL directions are blocked  -> STOP
    """
    if state["goal_ahead"] and not state["front_blocked"]:
        return "FORWARD"
    if state["goal_on_left"] and not state["left_blocked"]:
        return "LEFT"
    if state["goal_on_right"] and not state["right_blocked"]:
        return "RIGHT"
    if not state["front_blocked"]:
        return "FORWARD"
    if not state["left_blocked"]:
        return "LEFT"
    if not state["right_blocked"]:
        return "RIGHT"
    return "STOP"


def run_simulation():
    """Run decide_next_move against all possible scenarios.

    Returns a report dict with total/passed/failed counts, success rate and
    per-scenario results.
    """
    scenarios = [
        dict(zip(STATE_KEYS, bits))
        for bits in itertools.product([False, True], repeat=len(STATE_KEYS))
    ]

    results = []
    passed = 0
    total = len(scenarios)

    for state in scenarios:
        expected = expected_action(state)
        try:
            actual = decide_next_move(state)
        except Exception as exc:  # noqa: BLE001 - report any crash
            actual = f"CRASH: {exc!r}"

        ok = actual in VALID_ACTIONS and actual == expected
        if ok:
            passed += 1

        results.append(
            {
                "state": state,
                "expected": expected,
                "actual": actual,
                "valid_action": actual in VALID_ACTIONS,
                "passed": bool(ok),
            }
        )

    failed = total - passed
    report = {
        "total_scenarios": total,
        "passed": passed,
        "failed": failed,
        "success_rate": round(passed / total, 4) if total else 0.0,
        "results": results,
    }
    return report


def main() -> None:
    report = run_simulation()

    os.makedirs(ARTIFACTS_DIR, exist_ok=True)
    with open(REPORT_PATH, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2, ensure_ascii=False)

    print(f"Simulation report saved to: {REPORT_PATH}\n")
    print(f"Total scenarios : {report['total_scenarios']}")
    print(f"Passed          : {report['passed']}")
    print(f"Failed          : {report['failed']}")
    print(f"Success rate    : {report['success_rate']:.2%}")


if __name__ == "__main__":
    main()
