"""
reviewer_agent.py
=================
Reviewer Agent for the SCSE '26 Integration and Simulation project.

Reviews the simulation report generated by runner.py, identifies problems
based on the report, and recommends improvements.

Output schema (strict JSON):
{
  "issue": "string",
  "likely_cause": "string",
  "recommendation": "string",
  "needs_revision": true|false
}
"""

import json
import os
import re
from typing import Any, Dict

import dashscope

dashscope.api_key = os.getenv("DASHSCOPE_API_KEY")

REQUIRED_REVIEW_KEYS = {"issue", "likely_cause", "recommendation", "needs_revision"}

SYSTEM_PROMPT = """You are a Reviewer Agent in a multi-agent software system.

ROLE:
A simulation of the robot navigation logic (decide_next_move) has been run
against all possible scenarios. You review the simulation report, identify
problems, and recommend improvements.

TASK:
Analyze the simulation report JSON provided by the user and produce a SINGLE
JSON object with EXACTLY these four keys:
  - "issue": a string describing the most important problem found in the
    report, or "No issues found" if everything passed.
  - "likely_cause": a string describing the most likely cause of the issue
    (or "" if there is no issue).
  - "recommendation": a string recommending how to fix/improve (or "" if there
    is no issue).
  - "needs_revision": a boolean. true if the report shows any failed
    scenario (success_rate < 1.0), false otherwise.

CONSTRAINTS:
1. Base your analysis ONLY on the numbers in the simulation report.
2. Output ONLY the JSON object. No prose, no explanation, no markdown code
   fences (no ```json ... ```), no trailing comments.

OUTPUT STRUCTURE (copy this shape exactly):
{
  "issue": "...",
  "likely_cause": "...",
  "recommendation": "...",
  "needs_revision": true
}
"""


def _extract_json(text: str) -> str:
    """Pull the first balanced JSON object out of a model reply."""
    text = text.strip()
    if text.startswith("```"):
        text = re.sub(r"^```[a-zA-Z]*\s*\n?", "", text)
        text = re.sub(r"\s*```$", "", text).strip()

    start = text.find("{")
    end = text.rfind("}")
    if start == -1 or end == -1 or end < start:
        raise ValueError(f"No JSON object found in model output:\n{text}")
    return text[start : end + 1]


def validate_review(data: Any) -> Dict[str, Any]:
    """Validate the Reviewer Agent's output.

    Checks: dict, exactly the four required keys, "needs_revision" is a
    boolean, and the remaining keys are strings.
    """
    if not isinstance(data, dict):
        raise TypeError(f"Expected a dict, got {type(data).__name__}")

    actual_keys = set(data.keys())
    missing = REQUIRED_REVIEW_KEYS - actual_keys
    extra = actual_keys - REQUIRED_REVIEW_KEYS
    if missing:
        raise ValueError(f"Missing required keys: {sorted(missing)}")
    if extra:
        raise ValueError(f"Unexpected extra keys introduced by Qwen: {sorted(extra)}")

    if not isinstance(data["needs_revision"], bool):
        raise TypeError("'needs_revision' must be a boolean")

    for key in ("issue", "likely_cause", "recommendation"):
        if not isinstance(data[key], str):
            raise TypeError(f"'{key}' must be a string")

    return data


def _call_qwen(report_json: str, extra_instruction: str = "") -> str:
    user_content = f"Simulation report:\n\n{report_json}"
    if extra_instruction:
        user_content += f"\n\n---\n{extra_instruction}"

    response = dashscope.Generation.call(
        model="qwen-turbo",
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": user_content},
        ],
        result_format="message",
    )
    return response.output.choices[0].message.content


def run_reviewer(simulation_report: Dict[str, Any], max_retries: int = 2) -> Dict[str, Any]:
    """Run the Reviewer Agent.

    Takes the simulation report, sends it to the Reviewer Agent, and returns
    the validated output.
    """
    if not dashscope.api_key:
        raise RuntimeError(
            "DASHSCOPE_API_KEY is not set. Export it before running, e.g.\n"
            '  PowerShell:  $env:DASHSCOPE_API_KEY = "sk-..."\n'
            "  bash/zsh:    export DASHSCOPE_API_KEY=sk-..."
        )

    report_json = json.dumps(simulation_report, indent=2, ensure_ascii=False)
    extra_instruction = ""
    last_error: Exception | None = None

    for attempt in range(max_retries + 1):
        raw = _call_qwen(report_json, extra_instruction)
        try:
            data = json.loads(_extract_json(raw))
            return validate_review(data)
        except json.JSONDecodeError as exc:
            last_error = ValueError(f"Qwen returned invalid JSON: {exc}\nRaw: {raw}")
        except (ValueError, TypeError) as exc:
            last_error = exc

        extra_instruction = (
            f"Your previous output was not valid: {last_error}\n"
            f"Return ONLY a single valid JSON object with EXACTLY the keys "
            f"{sorted(REQUIRED_REVIEW_KEYS)} and correct types, no extra text."
        )

    raise RuntimeError(
        f"Reviewer Agent failed after {max_retries + 1} attempts: {last_error}"
    )
