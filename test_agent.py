"""
test_agent.py
=============
Test Agent for the SCSE '26 Integration and Simulation project.

The Test Agent is responsible for creating pytest-style tests for the
decide_next_move(state) function generated by the Developer Agent, based on:
  - the requirements artifact (from the Analyst Agent),
  - the plan artifact (from the Planner Agent).

The generated tests must cover all the possible scenarios and make sure
decide_next_move works as expected.
"""

import ast
import json
import os
import re
from typing import Any, Dict

import dashscope

# API key from environment -- never hard-code secrets.
dashscope.api_key = os.getenv("DASHSCOPE_API_KEY")

# --- Prompt: role, task, constraints, output structure ---------------------
SYSTEM_PROMPT = """You are a Test Agent in a multi-agent software system.

ROLE:
The Analyst Agent produced requirements, the Planner Agent produced a
navigation plan, and the Developer Agent produced a function
decide_next_move(state). Your job is to write pytest-style tests that verify
decide_next_move works correctly for ALL possible scenarios.

INPUT STRUCTURE OF decide_next_move:
decide_next_move takes a single argument `state`, a dict with six boolean keys:
  - "goal_ahead": True if the goal is directly ahead
  - "goal_on_left": True if the goal is to the left
  - "goal_on_right": True if the goal is to the right
  - "front_blocked": True if the path in front is blocked
  - "left_blocked": True if the path to the left is blocked
  - "right_blocked": True if the path to the right is blocked

It returns exactly one of: "FORWARD", "LEFT", "RIGHT", "STOP".

EXPECTED BEHAVIOUR (from requirements and plan, with obstacle avoidance):
1. Prefer moving toward the goal whenever it can be done safely:
   - goal ahead and front not blocked -> FORWARD
   - goal on left and left not blocked -> LEFT
   - goal on right and right not blocked -> RIGHT
2. Never move into a blocked direction.
3. To reach the goal in a real environment the robot must navigate AROUND
   obstacles: if the goal direction is blocked but another direction is clear,
   pick a clear direction to manoeuvre (prefer FORWARD, then LEFT, then RIGHT).
4. Only if ALL directions are blocked -> STOP.

EXPECTED ACTION DECISION TABLE (derive every expected action from this
exact order -- do not replace it with a simpler rule):
    if goal_ahead and not front_blocked:      FORWARD
    elif goal_on_left and not left_blocked:   LEFT
    elif goal_on_right and not right_blocked: RIGHT
    elif not front_blocked:                   FORWARD
    elif not left_blocked:                    LEFT
    elif not right_blocked:                   RIGHT
    else:                                     STOP

CONSTRAINTS AND RULES:
1. Write pytest-style tests: import the function, define test functions named
   test_*, and use assert statements.
2. Import decide_next_move from the generated module, for example:
       from generated.navigation_logic import decide_next_move
3. Cover all possible scenarios: the six booleans give 64 states -- enumerate
   all of them (e.g. with itertools.product), plus assert that every returned
   action is a valid action and the correct expected move.
4. Output ONLY the raw Python test code. No prose, no explanation, no markdown
   code fences (no ```python ... ```), no comments that are not inside the code.
5. The code must be syntactically valid Python 3 and must be runnable by
   pytest (test functions discoverable).

Output the raw Python test code only.
"""


def _extract_code(text: str) -> str:
    """Extract Python source from a model reply (fences/prose-tolerant)."""
    text = text.strip()

    fence_match = re.search(r"```[a-zA-Z]*\n(.*?)```", text, re.DOTALL)
    if fence_match:
        code = fence_match.group(1)
    else:
        lines = text.splitlines()
        start_idx = 0
        for i, line in enumerate(lines):
            stripped = line.lstrip()
            if stripped.startswith(("def ", "class ", "import ", "from ", "#")):
                start_idx = i
                break
        code = "\n".join(lines[start_idx:])

    return code.strip() + "\n"


def validate_test_code(code: Any) -> str:
    """Validate the test code generated by the Test Agent.

    Checks:
      * code is a non-empty string
      * it does not contain markdown fences
      * it parses as valid Python
      * it contains the necessary keywords: an import statement, a test
        function definition, and test assertions
    """
    if not isinstance(code, str) or not code.strip():
        raise TypeError("Test Agent returned empty or non-string code")

    if "```" in code:
        raise ValueError("Test code must not contain markdown fences")

    try:
        ast.parse(code)
    except SyntaxError as exc:
        raise ValueError(f"Generated test code is not valid Python: {exc}") from exc

    if "import" not in code:
        raise ValueError("Test code must contain an import statement")

    if "def test_" not in code:
        raise ValueError("Test code must define at least one test function (def test_...)")

    if "assert" not in code:
        raise ValueError("Test code must contain test assertions (assert)")

    return code


def _call_qwen(requirements: Dict, plan: Dict, extra_instruction: str = "") -> str:
    """Send the system prompt + requirements + plan to Qwen, return raw text."""
    user_content = (
        "Requirements artifact:\n"
        f"{json.dumps(requirements, indent=2, ensure_ascii=False)}\n\n"
        "Plan artifact:\n"
        f"{json.dumps(plan, indent=2, ensure_ascii=False)}"
    )
    if extra_instruction:
        user_content += f"\n\n---\n{extra_instruction}"

    response = dashscope.Generation.call(
        model="qwen-turbo",
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": user_content},
        ],
        result_format="message",
    )
    return response.output.choices[0].message.content


def run_test_agent(requirements: Dict[str, Any], plan: Dict[str, Any], max_retries: int = 2) -> str:
    """Run the Test Agent.

    Takes the requirements and the plan, sends them to the Test Agent, and
    returns the generated test code after validation. Retries with a
    correction instruction if the output does not validate.
    """
    if not dashscope.api_key:
        raise RuntimeError(
            "DASHSCOPE_API_KEY is not set. Export it before running, e.g.\n"
            '  PowerShell:  $env:DASHSCOPE_API_KEY = "sk-..."\n'
            "  bash/zsh:    export DASHSCOPE_API_KEY=sk-..."
        )

    extra_instruction = ""
    last_error: Exception | None = None

    for attempt in range(max_retries + 1):
        raw = _call_qwen(requirements, plan, extra_instruction)
        try:
            code = _extract_code(raw)
            return validate_test_code(code)
        except (ValueError, TypeError) as exc:
            last_error = exc

        extra_instruction = (
            f"Your previous output was not valid test code: {last_error}\n"
            f"Return ONLY raw, syntactically valid pytest code that imports "
            f"decide_next_move, defines test functions (def test_...), and uses "
            f"assert. No prose, no markdown fences."
        )

    raise RuntimeError(
        f"Test Agent failed after {max_retries + 1} attempts: {last_error}"
    )
